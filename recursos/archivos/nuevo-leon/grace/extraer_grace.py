#!/usr/bin/env python3
"""Extract an unaveraged Nuevo Leon rectangle and CSV from the verified JPL source.

Requires netCDF4 and numpy. AI-assisted code; no scientific values are generated.
"""
import argparse
import csv
import hashlib
from pathlib import Path

import numpy as np
from netCDF4 import Dataset, num2date

SOURCE_SHA256 = '3522dd579cc10326339efdecece550ba01f41b9bee599d0ed915fc35f9eafb64'
SUBSET_NAME = 'nuevo-leon-grace-jpl-rl06.3-v04-2002-2026-09.nc'
CSV_NAME = 'nuevo-leon-grace-jpl-rl06.3-v04-2002-2026-09.csv'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    if hashlib.sha256(args.source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise SystemExit('Source SHA-256 does not match the documented JPL release.')
    args.output_dir.mkdir(parents=True, exist_ok=True)
    ncpath, csvpath = args.output_dir / SUBSET_NAME, args.output_dir / CSV_NAME
    if ncpath.exists() or csvpath.exists():
        raise SystemExit('Refusing to overwrite existing extraction outputs; choose a new directory.')
    with Dataset(args.source) as src:
        # Preserve stored values, including fill values; do not apply any scale factors.
        src.set_auto_maskandscale(False)
        lat, lon = src['lat'][:], src['lon'][:]
        westlon = (lon + 180) % 360 - 180
        iy = np.flatnonzero((lat >= 23.1) & (lat <= 27.8))
        ix = np.flatnonzero((westlon >= -101.2) & (westlon <= -98.4))
        assert len(iy) and len(ix)
        assert np.all(np.diff(iy) == 1) and np.all(np.diff(ix) == 1)
        selectors = {'lat': slice(int(iy[0]), int(iy[-1]) + 1),
                     'lon': slice(int(ix[0]), int(ix[-1]) + 1)}
        with Dataset(ncpath, 'w', format='NETCDF4') as out:
            out.setncatts({a: src.getncattr(a) for a in src.ncattrs()})
            out.setncattr('raack_source_sha256', SOURCE_SHA256)
            out.setncattr('raack_subset_method', 'Grid centers inside 23.1 <= lat <= 27.8 and -101.2 <= lon <= -98.4; no averaging, interpolation, or scale-factor application. Original 0..360 longitude convention retained.')
            out.setncattr('raack_ai_use', 'Codex assisted extraction code and documentation. Scientific values are copied from the JPL source, not generated by AI.')
            out.setncattr('geospatial_lat_min', float(lat[iy].min()))
            out.setncattr('geospatial_lat_max', float(lat[iy].max()))
            out.setncattr('geospatial_lon_min', float(lon[ix].min()))
            out.setncattr('geospatial_lon_max', float(lon[ix].max()))
            for name, dim in src.dimensions.items():
                length = len(iy) if name == 'lat' else len(ix) if name == 'lon' else len(dim)
                out.createDimension(name, None if dim.isunlimited() else length)
            for name, v in src.variables.items():
                kw = {'zlib': True, 'complevel': 4}
                if '_FillValue' in v.ncattrs():
                    kw['fill_value'] = v.getncattr('_FillValue')
                dest = out.createVariable(name, v.dtype, v.dimensions, **kw)
                dest.setncatts({a: v.getncattr(a) for a in v.ncattrs() if a != '_FillValue'})
                dest.set_auto_maskandscale(False)
                dest[:] = v[tuple(selectors.get(d, slice(None)) for d in v.dimensions)]
        dates = num2date(src['time'][:], units=src['time'].units, calendar=src['time'].calendar)
        def cell(v, key):
            value = v[key]
            if not np.isfinite(value) or ('_FillValue' in v.ncattrs() and value == v.getncattr('_FillValue')):
                return ''
            return float(value)
        with csvpath.open('w', newline='', encoding='utf-8') as f:
            writer = csv.writer(f)
            writer.writerow(['time_utc', 'time_days_since_2002_01_01', 'month', 'latitude', 'longitude',
                             'lwe_thickness_cm', 'uncertainty_cm', 'scale_factor', 'mascon_ID'])
            for it, date in enumerate(dates):
                for y in iy:
                    for x in ix:
                        writer.writerow([date.strftime('%Y-%m-%dT%H:%M:%SZ'), float(src['time'][it]),
                                         date.strftime('%Y-%m'), float(lat[y]), float(westlon[x]),
                                         cell(src['lwe_thickness'], (it, y, x)),
                                         cell(src['uncertainty'], (it, y, x)),
                                         cell(src['scale_factor'], (y, x)),
                                         cell(src['mascon_ID'], (y, x))])
    print(f'{ncpath}\n{csvpath}\n{len(dates)} time steps × {len(iy)} latitudes × {len(ix)} longitudes')


if __name__ == '__main__':
    main()
