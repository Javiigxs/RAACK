/** Traduce una clave; `{nombre}` se sustituye por el parámetro correspondiente. */
export function t(key: string, params?: Record<string, string | number | null | undefined>): string {
  let s = dict[ui.lang][key] ?? dict.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v === null || v === undefined ? '—' : String(v));
  }
  return s;
}

/** Traduce `key` si existe; si no, usa `fallback`. */
export function tOr(key: string, fallback: string): string {
  return dict[ui.lang][key] ?? dict.en[key] ?? t(fallback);
}

export function hasKey(key: string): boolean {
  return key in dict.en;
}

